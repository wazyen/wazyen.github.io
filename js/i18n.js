let currentLanguage = DEFAULT_LANGUAGE;
const changeListeners = [];

export function getCurrentLanguage() {
	return currentLanguage;
}

export function onLanguageChange(fn) {
	if (typeof fn === 'function') {
		changeListeners.push(fn);
	}
}

export function applyTranslations(lang) {
	const dict = translations[lang] || translations[DEFAULT_LANGUAGE];

	// Update page title if appropriate key exists
	const isAcademicPage = window.location.pathname.includes('academic.html');
	const titleKey = isAcademicPage ? 'meta.title.academic' : 'meta.title.index';
	if (dict[titleKey]) {
		document.title = dict[titleKey];
	}

	// Update elements with data-i18n (textContent)
	document.querySelectorAll('[data-i18n]').forEach(el => {
		const key = el.getAttribute('data-i18n');
		if (dict[key] !== undefined) {
			el.textContent = dict[key];
		}
	});

	// Update elements with data-i18n-html (innerHTML for bold tags, etc.)
	document.querySelectorAll('[data-i18n-html]').forEach(el => {
		const key = el.getAttribute('data-i18n-html');
		if (dict[key] !== undefined) {
			el.innerHTML = dict[key];
		}
	});

	if (window.lucide) {
		lucide.createIcons();
	}
}

export function updateSwitcherButtons(lang) {
	document.querySelectorAll('[data-lang-btn]').forEach(btn => {
		const btnLang = btn.getAttribute('data-lang-btn');
		if (btnLang === lang) {
			btn.className = "px-2 py-1 rounded transition-colors text-white bg-indigo-600 font-semibold shadow-sm";
		} else {
			btn.className = "px-2 py-1 rounded transition-colors text-slate-600 hover:text-slate-900 hover:bg-slate-200 dark:text-slate-400 dark:hover:text-white dark:hover:bg-slate-800";
		}
	});
}

export function setLanguage(lang) {
	if (!SUPPORTED_LANGUAGES.includes(lang)) {
		lang = DEFAULT_LANGUAGE;
	}
	currentLanguage = lang;
	localStorage.setItem('preferred_language', lang);
	document.documentElement.lang = lang;

	// Sync URL search param
	const url = new URL(window.location.href);
	if (url.searchParams.get('lang') !== lang) {
		url.searchParams.set('lang', lang);
		window.history.replaceState({}, '', url.toString());
	}

	updateSwitcherButtons(lang);
	applyTranslations(lang);

	// Trigger registered listeners
	changeListeners.forEach(listener => {
		try {
			listener(lang);
		} catch (e) {
			console.error('Error in language change listener:', e);
		}
	});
}

export function getLocalizedDataUrl(filename, lang = currentLanguage) {
	return `data/${lang}/${filename}.json`;
}

export function initI18n() {
	const urlParams = new URLSearchParams(window.location.search);
	const langFromUrl = urlParams.get('lang');
	const langFromStorage = localStorage.getItem('preferred_language');

	let initialLang = DEFAULT_LANGUAGE;
	if (langFromUrl && SUPPORTED_LANGUAGES.includes(langFromUrl)) {
		initialLang = langFromUrl;
	} else if (langFromStorage && SUPPORTED_LANGUAGES.includes(langFromStorage)) {
		initialLang = langFromStorage;
	} else if (navigator.language) {
		const browserLang = navigator.language.toLowerCase();
		if (browserLang.startsWith('ca')) {
			initialLang = 'ca';
		} else if (browserLang.startsWith('es')) {
			initialLang = 'es';
		}
	}

	// Setup click listeners for language switcher buttons
	document.querySelectorAll('[data-lang-btn]').forEach(btn => {
		btn.addEventListener('click', (e) => {
			e.preventDefault();
			const selected = btn.getAttribute('data-lang-btn');
			if (selected && selected !== currentLanguage) {
				setLanguage(selected);
			}
		});
	});

	setLanguage(initialLang);
}
